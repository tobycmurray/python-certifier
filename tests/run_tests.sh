#!/usr/bin/env bash
# Requires: bash >= 4 (associative arrays)

# script for testing the Python certifier.
# Supports running two kinds of tests:
# "all" - here, we run the certifier over all of the test inputs of a model (e.g., 10000 MNIST test images).
#         we check whether the real-arithmetic Python certifier agrees with the Dafny reference implementation
#
# "cex" - here, we run the certifier over counter-examples to the Dafny certifier
#         we check that the Python certifier does not certify any counter-examples, but that the real-arithmetic Python
#         certifier would have certified all of them

# --- version guard ---------------------------------------------------------
if [[ -z ${BASH_VERSINFO-} || ${BASH_VERSINFO[0]} -lt 4 ]]; then
  echo "ERROR: This script requires Bash >= 4."
  echo "       On macOS, install with:  brew install bash"
  echo "       Then run with:           /opt/homebrew/bin/bash $0"
  exit 1
fi

set -euo pipefail

# --- configuration ---------------------------------------------------------

CERTIFIER=../robust_certifier.py

# Optional first arg: restrict to models whose name starts with it
# (e.g. "mnist" -> mnist + mnist_biased_*; "fashion_mnist" -> fashion + its biased).
# Lets us run one model's suite at a time (single-threaded, low contention with
# any concurrent norm computation). Empty -> run everything.
MODEL_FILTER="${1:-}"
# Optional env vars (additive, 2026-11-05): KIND_FILTER="all,cex" restricts to the listed
# kinds (all/first100/cex/natgrid); MODEL_SKIP="higgs_w1024_500k ..." skips the listed model
# keys exactly (MODEL_FILTER is a prefix match, so "higgs_w1024" also selects higgs_w1024_500k).
# Both are used by tests/run_job.sh; empty = no restriction.
KIND_FILTER="${KIND_FILTER:-}"
MODEL_SKIP="${MODEL_SKIP:-}"

# Optional env var SKIP_EXISTING=1: skip any test whose JSON output already
# exists (and is non-empty) AND is newer than its input set. Lets us iterate on
# newly-added tests without re-running the established MNIST/Fashion/CIFAR suite
# (whose outputs are already present). Applies uniformly to all kinds (every run
# writes --json-output). An output older than its inputs (a regenerated suite) is
# re-run automatically; delete an output to force a re-run for any other reason.
SKIP_EXISTING="${SKIP_EXISTING:-}"

# Optional env var NUMPY_EXEC=1: certify the IEEE-754-compliant numpy execution
# instead of the Keras one. Every test's inputs are remapped to their _numpy
# variants (y1 from compliant_forward; generated by models/provision_numpy_all_inputs.sh
# for the "all"/first100 sets and scripts/generate_numpy_cexs.sh [in
# verified-certified-robustness] for the cex suites; the biased models' "all"
# runs use the *_numpy_biased_* files carrying the biased execution's own y1).
# Hybrid modes get --numpy-exec so the measurement passes run the same compliant
# execution. Outputs go to json_results_numpy/ (first100: json_results_first100_numpy/)
# so the Keras timing numbers are never overwritten. Any test whose numpy
# variant does not exist yet (z3; cex suites still being generated) is skipped
# with a message -- rerun once generated (SKIP_EXISTING=1 avoids repeats).
NUMPY_EXEC="${NUMPY_EXEC:-}"

# Optional env var DRY_RUN=1: print, one per line, the exact certifier command line
# (argv) of every test the invocation would run, and run nothing: no norm staging, no
# output directory, no certifier. The skip messages (MODEL_FILTER, SKIP_EXISTING, missing
# numpy variants) are printed exactly as in a real run, so two invocations are equivalent
# iff their DRY_RUN=1 outputs are identical (used to check the registry refactor and the
# job wrapper tests/run_job.sh against the superseded per-job wrappers).
DRY_RUN="${DRY_RUN:-}"

# Legacy per-instance Dafny/z3 results files (Tobler et al.'s pipeline). Only z3's and the
# MNIST gram-11 one are still wired in (REF_RESULTS below); the others are kept for the record.
MNIST_RESULTS_GRAM_11="results_epsilon_0.45_[128,128,128,128,128,128,128,128]_500_eval_0.3_gram_11.json"
MNIST_RESULTS_GRAM_20="results_epsilon_0.45_[128,128,128,128,128,128,128,128]_500_eval_0.3_gram_20.json"
FASHION_MNIST_RESULTS_GRAM_12="results_epsilon_0.26_[256,128,128,128,128,128,128,128,128,128,128,128]_500_eval_0.25_gram_12.json"
FASHION_MNIST_RESULTS_GRAM_13="results_epsilon_0.26_[256,128,128,128,128,128,128,128,128,128,128,128]_500_eval_0.25_gram_13.json"
CIFAR10_RESULTS_GRAM_12="results_epsilon_0.1551_[512,256,128,128,128,128,128,128]_800_eval_0.141_gram_12.json"
Z3_RESULTS_GRAM_10="z3_certifier_results_gram_10.json"
# z3: synthetic soundness check, not a model of the paper; stays inline (not in the registry).
Z3_NEURAL_NET="z3_neural_network.txt"
CEX_Z3_FLOAT32="z3_counter_examples.json"

# --- declarative tables, built from the model registry -----------------------
# Every per-model path comes from ../models/registry.tsv (one row per model key;
# loaders ../models/registry.sh and ../models/registry.py), so the table below is
# the registry's and not a copy of it:
#   NN_FILE[key]        = ../models/<net>          (sound-by-construction weights; gitignored,
#                         regenerated by ../models/provision_*.sh or extracted from ../provisioned/)
#   ALL_INPUTS[key]     = <inputs_all>              (full test set; the numpy variants are derived
#                         by numpy_variant() below)
#   REF_RESULTS[key:g]  = ../models/precomputed/<ref_rq1> at gram_rq1 (the per-model tightest
#                         gram the RQ1 cex/natgrid runs use: MNIST 20, Fashion 13, CIFAR 12) and
#                         <ref_all> at gram_all (uniform 12 for the RQ2/RQ3 full-set runs). The
#                         Dafny refs are norms-only runs: they supply the lipschitz_bounds the
#                         certifier cross-checks against, no per-instance verdicts (see run_test).
#                         HIGGS/EMNIST have none -> the certifier's L_real baseline.
#   BIASES_FILE[key]    = <biases_txt>              (biased models only; the established biases.txt:
#                         the numpy cex generator exports a bit-identical one)
#   CEX[key:format]     = cex_<dataset>_<format>[_biased_<bias>_<bias_pos>]/counter_examples.json
#                         for each format in <cex_formats>. No cifar10:float16 -- by policy, not
#                         evaluated: its input layer has n*u = 1.5 >= 1 (3072 * 2^-11), where the
#                         bound stays sound but is useless (the certifier refuses, see
#                         robust_certifier.check_rounding_preconditions; reaffirmed 2026-11-04).
#                         The float16 CIFAR-10 suite exists (verified-certified-robustness
#                         scripts/regen_cifar10_float16_suite.sh); the paper reports its radii in
#                         §2.2 only.
#   NATGRID[key]        = <inputs_dir>/natgrid_numpy_biased_<bias>_<bias_pos>.json (biased models:
#                         the certified biased-model test images the k/255-grid search
#                         (natural_grid_cexs.py in verified-certified-robustness) refutes at the
#                         standard radii -- MNIST 24, Fashion 204, CIFAR 370; subsets of the biased
#                         numpy "all" sets, built and cross-checked by make_natgrid_inputs.py;
#                         numpy execution only)
# shellcheck source=../models/registry.sh
source ../models/registry.sh

declare -A NN_FILE=( [z3]="$Z3_NEURAL_NET" )
declare -A BIASES_FILE=()
declare -A REF_RESULTS=(
  ["z3:10"]="$Z3_RESULTS_GRAM_10"
  # legacy
  ["mnist:11"]="$MNIST_RESULTS_GRAM_11"
  ["mnist_biased_1e6_end:11"]="$MNIST_RESULTS_GRAM_11"
)
declare -A ALL_INPUTS=()
declare -A CEX=( ["z3:float32"]="$CEX_Z3_FLOAT32" )
declare -A NATGRID=()

for _key in $(registry_keys); do
  NN_FILE[$_key]="../models/$(registry_get "$_key" net)"
  ALL_INPUTS[$_key]="$(registry_get "$_key" inputs_all)"
  _g="$(registry_get "$_key" gram_rq1)"; _r="$(registry_get "$_key" ref_rq1)"
  if [[ "$_g" != "-" && "$_r" != "-" ]]; then REF_RESULTS["$_key:$_g"]="../models/precomputed/$_r"; fi
  _g="$(registry_get "$_key" gram_all)"; _r="$(registry_get "$_key" ref_all)"
  if [[ "$_g" != "-" && "$_r" != "-" ]]; then REF_RESULTS["$_key:$_g"]="../models/precomputed/$_r"; fi
  _dataset="$(registry_get "$_key" dataset)"
  _bias="$(registry_get "$_key" bias)"; _pos="$(registry_get "$_key" bias_pos)"
  _sfx=""
  if [[ "$_bias" != "-" ]]; then
    _sfx="_biased_${_bias}_${_pos}"
    BIASES_FILE[$_key]="$(registry_get "$_key" biases_txt)"
    NATGRID[$_key]="$(registry_get "$_key" inputs_dir)/natgrid_numpy${_sfx}.json"
  fi
  _fmts="$(registry_get "$_key" cex_formats)"
  if [[ "$_fmts" != "-" ]]; then
    for _fmt in ${_fmts//,/ }; do
      CEX["$_key:$_fmt"]="cex_${_dataset}_${_fmt}${_sfx}/counter_examples.json"
    done
  fi
done
unset _key _g _r _dataset _bias _pos _sfx _fmts _fmt

# First 100 test points (= ERAN's 100; indices 0-99) for the same-100-point ERAN
# comparison (RQ3 Table 3b). Kind "first100" runs these and writes to
# json_results_first100/ (named *_all.json so compute_vra consumes them when
# pointed at that dir).
declare -A ALL_INPUTS_100=(
  [mnist]="all_mnist_test_inputs/test_inputs_epsilon_0.3_first100.json"
  [fashion_mnist]="all_fashion_mnist_test_inputs/test_inputs_epsilon_0.25_first100.json"
  [cifar10]="all_cifar10_test_inputs/all_test_inputs_first100.json"
  # EMNIST first-100 = the leading 100 of each full inputs.json (same points ERAN uses);
  # kept inside the full dir so its per-instance orig_*_x_*.npy files resolve.
  [emnist_byclass_full]="inputs_emnist_byclass_full/inputs_first100.json"
  [emnist_balanced_full]="inputs_emnist_balanced_full/inputs_first100.json"
)

# --- helpers ---------------------------------------------------------------

die() { echo "ERROR: $*" >&2; exit 1; }

# Per-test certifier log. Overridable so that two run_tests.sh invocations can share
# tests/ at the same time (e.g. the float16 full-set runner and an RQ1 suite runner).
RUNLOG="${RUNLOG:-.log}"
# Per-run count summaries (see run_test); one TSV per model, lines appended per run.
SUMMARY_DIR="${SUMMARY_DIR:-summary}"

# NUMPY_EXEC input remapping. "all"/"first100" files gain a _numpy suffix
# (biased models map to the _numpy_biased_* variants, whose y1 is the biased
# numpy execution's own); cex dirs gain a _numpy sibling. Prints the mapped
# path; returns 1 if no numpy variant scheme exists (z3's bare cex file).
numpy_variant() {  # model kind file [format]
  local model="$1" kind="$2" file="$3" format="${4:-float32}"
  # float64 "all" sets carry y1 from the compliant numpy execution AT FLOAT64 of the
  # same float32-weighted network (models/provision_numpy64_all_inputs.sh); their
  # files are the _numpy64 siblings of the float32 _numpy ones.
  # Likewise the float16 "all" sets (models/provision_numpy16_all_inputs.sh): y1 from the
  # compliant numpy execution AT FLOAT16 (weights cast down to float16), files _numpy16.
  local sfx="_numpy"; [[ "$format" == "float64" ]] && sfx="_numpy64"; [[ "$format" == "float16" ]] && sfx="_numpy16"
  # natgrid sets are built from the numpy biased "all" sets: already the numpy variant.
  if [[ "$kind" == "natgrid" ]]; then echo "$file"; return 0; fi
  if [[ "$kind" == "cex" ]]; then
    [[ "$file" == */counter_examples.json ]] || return 1
    echo "${file%/counter_examples.json}_numpy/counter_examples.json"
    return 0
  fi
  local base="${file%.json}"
  case "$model" in
    mnist_biased_1e6_end)         echo "${base}_numpy_biased_1e6_end.json" ;;
    fashion_mnist_biased_3e6_end) echo "${base}_numpy_biased_3e6_end.json" ;;
    cifar10_biased_4e6_end)       echo "${base}_numpy_biased_4e6_end.json" ;;
    *)                            echo "${base}${sfx}.json" ;;
  esac
}

grabnum() {
  # $1: grep -E pattern
  local pat="$1" out=""
  # Extract the first integer from the first matching line
  out=$(grep -E -- "$pat" "$RUNLOG" | head -n1 | grep -Eo '[0-9]+' | head -n1 || true)
  if [[ -z "$out" ]]; then
    echo "ERROR: Could not parse '$pat' from $RUNLOG" >&2
    echo "------- $RUNLOG tail -------" >&2
    tail -n 40 "$RUNLOG" | sed 's/^/| /' >&2 || true
    echo "-------------------------" >&2
    exit 1
  fi
  printf '%s\n' "$out"
}

# --- main runner -----------------------------------------------------------

run_test() {
  local format="$1" model="$2" gram="$3" kind="$4" mode="$5"

  # optional model filter (run one model's suite at a time)
  if [[ -n "$MODEL_FILTER" && "$model" != "$MODEL_FILTER"* ]]; then return 0; fi
  if [[ -n "$MODEL_SKIP" && " $MODEL_SKIP " == *" $model "* ]]; then return 0; fi
  if [[ -n "$KIND_FILTER" && ",$KIND_FILTER," != *",$kind,"* ]]; then return 0; fi

  # lookups (use presence check that works on bash >= 4.0)
  [[ -n ${NN_FILE[$model]+x} ]] || die "Unknown model '$model'. Known: ${!NN_FILE[*]}"
  local nn_file="${NN_FILE[$model]}"

  # The Dafny reference is OPTIONAL. Models with no REF_RESULTS entry at all
  # (the HIGGS/EMNIST models) certify against the computed L_real as the
  # real-arithmetic baseline (robust_certifier's dafny_ref is omitted). But if a
  # model HAS refs for some grams and this gram isn't one of them, that's almost
  # certainly a typo -- die with the available grams.
  local key_ref="$model:$gram"
  local ref_results_file=""
  local has_any_ref=0 k
  for k in "${!REF_RESULTS[@]}"; do
    [[ $k == "$model:"* ]] && { has_any_ref=1; break; }
  done
  if [[ -n ${REF_RESULTS[$key_ref]+x} ]]; then
    ref_results_file="${REF_RESULTS[$key_ref]}"
  elif (( has_any_ref )); then
    local grams=()
    for k in "${!REF_RESULTS[@]}"; do
      [[ $k == "$model:"* ]] && grams+=("${k#"$model:"}")
    done
    die "Unknown gram '$gram' for '$model'. Available: ${grams[*]:-(none)}"
  fi
  # else: no ref for this model -> no-ref (L_real baseline) mode.

  local cex_file=""
  case "$kind" in
    all)
      # float32 always; float64/float16 only under NUMPY_EXEC (their inputs are the
      # _numpy64/_numpy16 sets, whose y1 come from the compliant execution at that format).
      [[ "$format" == "float32" || ( ( "$format" == "float64" || "$format" == "float16" ) && -n "$NUMPY_EXEC" ) ]] \
        || die "Only float32 (or float64/float16 under NUMPY_EXEC=1) supported when running kind 'all'"
      [[ -n ${ALL_INPUTS[$model]+x} ]] || die "No ALL inputs configured for '$model'"
      cex_file="${ALL_INPUTS[$model]}"
      ;;
    first100)
      [[ "$format" == "float32" ]] || die "Only float32 format supported when running kind 'first100'"
      [[ -n ${ALL_INPUTS_100[$model]+x} ]] || die "No first-100 inputs configured for '$model'"
      cex_file="${ALL_INPUTS_100[$model]}"
      ;;
    cex)
      local key_cex="$model:$format"
      [[ -n ${CEX[$key_cex]+x} ]] || die "Unsupported format '$format' for '$model' and kind 'cex'"
      cex_file="${CEX[$key_cex]}"
      ;;
    natgrid)
      [[ "$format" == "float32" && -n "$NUMPY_EXEC" ]] \
        || die "kind 'natgrid' is float32 under NUMPY_EXEC=1 only (the grid instances were judged under the compliant numpy float32 execution)"
      [[ -n ${NATGRID[$model]+x} ]] || die "No natgrid inputs configured for '$model'"
      cex_file="${NATGRID[$model]}"
      ;;
    *)
      die "Unrecognised kind '$kind'. Should be 'all', 'first100', 'cex' or 'natgrid'."
      ;;
  esac

  local mode_tag
  case "$mode" in
    standard)    mode_tag="standard"     ;;
    hybrid-only) mode_tag="hybrid_only"  ;;
    hybrid-meas) mode_tag="hybrid_meas"  ;;
    *) die "Unrecognised mode '$mode'. Should be 'standard', 'hybrid-only' or 'hybrid-meas'." ;;
  esac

  local bias_flag=""
  if [[ -n ${BIASES_FILE[$model]+x} ]]; then
    # Under NUMPY_EXEC the --biases file stays the established one: the numpy
    # cex generator exports a bit-identical biases.txt (the construction is
    # deterministic), and this one always exists.
    bias_flag="--biases ${BIASES_FILE[$model]}"
  fi

  # NUMPY_EXEC: remap inputs to the _numpy variants; skip whatever has no
  # variant (yet); hybrid modes measure via --numpy-exec.
  local numpy_flag=""
  if [[ -n "$NUMPY_EXEC" ]]; then
    local mapped
    if ! mapped=$(numpy_variant "$model" "$kind" "$cex_file" "$format"); then
      echo "Skipping (no numpy variant scheme) [$mode]: $format, $model, $gram, $kind"
      return 0
    fi
    if [[ ! -s "$mapped" ]]; then
      echo "Skipping (numpy variant not yet generated: $mapped) [$mode]: $format, $model, $gram, $kind"
      return 0
    fi
    cex_file="$mapped"
    if [[ "$mode" == hybrid-* ]]; then numpy_flag="--numpy-exec"; fi
  fi

  # first100 results go in their own dir, named *_all.json so compute_vra (pointed
  # at json_results_first100/) consumes them with no changes.
  local out_dir="json_results" out_kind="$kind"
  if [[ "$kind" == "first100" ]]; then out_dir="json_results_first100"; out_kind="all"; fi
  if [[ -n "$NUMPY_EXEC" ]]; then out_dir="${out_dir}_numpy"; fi
  local json_output="$out_dir/${mode_tag}_${model}_${format}_gram${gram}_${out_kind}.json"
  [[ -n "$DRY_RUN" ]] || mkdir -p "$out_dir"

  if [[ -n "$SKIP_EXISTING" && -s "$json_output" ]]; then
    # Never trust an output older than the input set it was produced from: a
    # regenerated suite (new counter_examples.json / inputs .json) must re-run.
    if [[ "$json_output" -ot "$cex_file" ]]; then
      echo "Re-running (output older than its inputs $cex_file) [$mode]: $format, $model, $gram, $kind"
    else
      echo "Skipping (output exists) [$mode]: $format, $model, $gram, $kind"
      return 0
    fi
  fi

  # shellcheck disable=SC2086
  # ${ref_results_file:+...} passes the Dafny ref ONLY when one is configured;
  # omitting it makes the certifier use L_real as the real-arithmetic baseline.
  local -a cmd=(python "$CERTIFIER" --mode "$mode" --json-output "$json_output" $bias_flag $numpy_flag "$format" "$nn_file" "$gram" "$cex_file" ${ref_results_file:+"$ref_results_file"})
  if [[ -n "$DRY_RUN" ]]; then
    echo "${cmd[*]}"
    return 0
  fi

  echo -n "Running test [$mode]: $format, $model, $gram, $kind ...  "
  "${cmd[@]}" > "$RUNLOG" 2>&1 || (cat "$RUNLOG"; die "Couldn't run python certifier")

  local count count_ok count_failed count_ok_real
  count=$(       grabnum 'Got [0-9]+ instances to certify'                                )
  count_ok=$(    grabnum 'Certified [0-9]+ instances as robust'                           )
  count_failed=$(grabnum 'Failed to certify [0-9]+ instances as robust'                   )
  count_ok_real=$(grabnum '(Real|Dafny) certifier would have certified [0-9]+ instances as robust' )

  (( count_ok + count_failed == count )) || die "Internal error: counts don't add up (ok=$count_ok failed=$count_failed total=$count)"

  # One summary line per run, appended to $SUMMARY_DIR/counts_<model>.tsv, in exactly the
  # format of reverify_audit_fixes.sh's run_one (the September record):
  #   name  got  certified  failed  real-certified  refused-overflow  refused-measuring
  # with "-" when the log has no such line (standard mode has no measuring pass).
  local count_ovf count_lg
  count_ovf=$(grep -Eo 'Refused [0-9]+ instances: overflow' "$RUNLOG" | grep -Eo '[0-9]+' || echo "-")
  count_lg=$(grep -Eo 'Refused [0-9]+ instances: measuring' "$RUNLOG" | grep -Eo '[0-9]+' || echo "-")
  mkdir -p "$SUMMARY_DIR"
  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "${mode_tag}_${model}_${format}_gram${gram}_${kind}" \
    "$count" "$count_ok" "$count_failed" "$count_ok_real" "$count_ovf" "$count_lg" >> "$SUMMARY_DIR/counts_${model}.tsv"

  if [[ "$kind" == "cex" || "$kind" == "natgrid" ]]; then
    (( count_ok == 0 )) || die "Certifier certified $count_ok counter-examples!"
    (( count_ok_real == count )) || die "Real-arithmetic certifier would not have certified all counter-examples!"
  else
    # kind is "all": no per-instance cross-check against Dafny. We did not run
    # Dafny over the test set (it would unconditionally recompute the norms, >1h).
    # The real-mode count uses the Dafny reference's lipschitz_bounds (L_ref) as
    # its baseline, so it reflects what the verified certifier would produce; our
    # own (transposed) norms are a hair tighter and their soundness rests on the
    # Coq formalisation (gram_iter_fp_sound / gram_iter_fp_sound_trmx).
    #
    # (Old check, re-enable if a per-instance Dafny test-set run is available:)
    #   local ref_num; ref_num=$(grep -c true "$ref_results_file")
    #   (( count_ok_real == ref_num )) || die "Mismatch vs Dafny reference: real=$count_ok_real ref=$ref_num ($ref_results_file)"
    :
  fi
  echo "OK"

  (grep -i warn "$RUNLOG") || echo -n ""

  echo ""
  awk '/CERTIFIER\ RESULTS/ {flag=1} flag' "$RUNLOG"
  echo ""
}

# --- stage precomputed norms into the run dir ------------------------------
# The certifier loads <hash>.<gram>.<method>.norms.json from its cwd (here,
# tests/). By default we stage the committed caches from ../models/precomputed/
# so the certifier reuses them instead of recomputing.
#
# Set RECOMPUTE_NORMS=1 to force a fresh norm computation instead: skip the
# staging AND clear any *.norms.json already cached in tests/, so every model's
# norms are recomputed and freshly TIMED (times_secs) into the cache. fp64 Gram
# norms are cheap now (a fraction of the whole run), so this is the mode to use
# for the clean single-threaded timing runs feeding §1 / the norm width-scaling
# figures. (Dafny reference files are dafny_*.json, not *.norms.json, so they are
# neither staged by the copy nor removed here.)
RECOMPUTE_NORMS="${RECOMPUTE_NORMS:-}"
if [[ -n "$DRY_RUN" ]]; then
  :   # DRY_RUN: neither stage nor clear anything
elif [[ -n "$RECOMPUTE_NORMS" ]]; then
  echo ">> RECOMPUTE_NORMS=1: not staging ../models/precomputed norms; clearing cached"
  echo ">> *.norms.json in $(pwd) to force fresh, timed recomputation."
  rm -f ./*.norms.json 2>/dev/null || true
else
  cp -f ../models/precomputed/*.norms.json . 2>/dev/null || true
fi

# --- test matrix -----------------------------------------------------------
# Each test is run in standard, hybrid-only, and hybrid-measured modes.
# hybrid-only and hybrid-measured both use a high-precision pre-deployment pass;
# hybrid-measured strictly dominates hybrid-only (it additionally tightens the
# E_ball term with measured radii), so hybrid-only is retained as an ablation
# midpoint to show how much the measured ball bound adds on top of the measured
# centre bound. Only the "all" runs feed the paper tables (via compute_vra.py);
# the "cex" runs are soundness checks (the tightest mode, hybrid-measured, must
# still reject every counter-example).
#
# GRAM SCHEME (corrected models):
#   RQ1 "cex" runs   -> per-model tightest gram: MNIST 20, Fashion 13, CIFAR 12
#                       (most stringent soundness test; E smallest there; each cex
#                        is certified at the gram its dafny ref/cexs were made at).
#   RQ2/RQ3 "all"    -> uniform gram 12 across all three models (past the data-
#                       independent norm-convergence point; cross-comparable).
# fp64-sound Gram norms make CIFAR's norm precompute cheap (~9 min), so its "all"
# and first100 tests are now active, as is the CIFAR float32 "cex" test (cexs
# regenerated against the gram-12 Dafny norms). Still disabled pending their own
# regeneration: CIFAR float64 cex and CIFAR biased cex (the old deepfool cexs are
# not counter-examples to the current verified certifier).

# ===== z3 (synthetic soundness check; gram 10) =====
run_test "float32" "z3"            "10" "cex" "standard"
run_test "float32" "z3"            "10" "cex" "hybrid-only"
run_test "float32" "z3"            "10" "cex" "hybrid-meas"

# ===== MNIST natural — cex (gram 20) =====
run_test "float32" "mnist"         "20" "cex" "standard"
run_test "float32" "mnist"         "20" "cex" "hybrid-only"
run_test "float32" "mnist"         "20" "cex" "hybrid-meas"
